#!/usr/bin/env python3
"""Single source of truth for the Digital Hub v2 ad timing.

Everything is driven by the recorded voice-over: phrase and word times come
from vo_words.json (take-relative, written by vo_align.py) and are shifted
onto the video by VO_OFFSET. The music grid (100 BPM, first downbeat at
GRID0) was fitted so the brand drop, the features lift, the trust section and
the CTA land on beats. index.html loads timeline.js (written by running this).
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
VO_OFFSET = 0.4                      # take 0.0 s plays at video 0.4 s
BPM = 100
BEAT = 60 / BPM                      # 0.6 s
BAR = BEAT * 4                       # 2.4 s
GRID0 = 0.19                         # video time of bar 0, beat 0
DURATION = 34.4

_vo = json.loads((HERE / "vo_words.json").read_text(encoding="utf-8"))


def ph(pid: str) -> float:
    """Video time a phrase starts."""
    return round(_vo[pid]["start"] + VO_OFFSET, 3)


def ph_end(pid: str) -> float:
    return round(_vo[pid]["end"] + VO_OFFSET, 3)


def w(pid: str, i: int) -> float:
    """Video time word i of a phrase starts."""
    return round(_vo[pid]["words"][i]["t"] + VO_OFFSET, 3)


def bar(n: float) -> float:
    return round(GRID0 + n * BAR, 3)


# scene windows (video seconds)
SCENES = {
    "s1": [0.0, 6.6], "s2": [6.6, 10.9], "s3": [10.9, 16.75],
    "s4": [16.75, 26.35], "s5": [26.35, 28.62], "s6": [28.62, DURATION],
}

CUES = {
    # 1 · the question
    "q1": [w("q1", i) for i in range(10)],
    "q1_out": ph("q2") - 0.32,
    "q2": [w("q2", i) for i in range(5)],
    "q_mark": w("q2", 4),
    # 2 · brand
    "b_kicker": ph("b1"),
    "b_converge": [ph("b1") + 0.25, bar(3) - (ph("b1") + 0.25)],   # dots fly in ...
    "b_logo": bar(3),                     # ... and lock on the music drop, a beat ahead of "ডিজিটাল"
    "b_word": w("b1", 3),
    "b_tag": [w("b2", i) for i in range(4)],
    # 3 · link -> similar website
    "l_head": [w("l1", i) for i in range(6)],
    "l_url": ph("l1") + 0.15,
    "l_type": [ph("l1") + 0.35, 1.3],
    "l_go": w("l1", 5),
    "l_src": w("l1", 5) + 0.2,
    "l_scan": [ph("l2") + 0.1, 2.2],
    "l_dst": ph("l2"),
    "l_blk": [ph("l2") + 0.45, ph("l2") + 0.95, ph("l2") + 1.45, ph("l2") + 1.95],
    "l_cap": [ph("l2"), w("l2", 3), w("l2", 5)],
    "l_ok": w("l2", 7),
    # 4 · features (one spotlight per spoken feature)
    "f_head": ph("f0"),
    "f": [ph("f1"), ph("f2"), ph("f3"), ph("f4"), ph("f5")],
    "f_end": [ph_end("f1"), ph_end("f2"), ph_end("f3"), ph_end("f4"), ph_end("f5")],
    # 5 · trust
    "t": ph("t1"), "t_shield": ph("t1") - 0.1, "t_recap": [ph("t1") + 0.45 + i * 0.16 for i in range(5)],
    # 6 · CTA + end card
    "c_line": [w("c1", i) for i in range(5)],
    "c_btn": ph("c2"), "c_press": w("c2", 1), "c_end": ph("c3"),
    "c_pulse": ph("c3") + 0.6,
}

MUSIC = {
    "drop_bar": 3,          # bar 3 = 7.39 s, on "ডিজিটাল"
    "lift_bar": 7,          # bar 7 = 16.99 s, features
    "trust_bar": 11,        # bar 11 = 26.59 s, breakdown
    "stop_beat": 52.5,      # music cuts out ...
    "final_beat": 53,       # ... and hits on "ডিজিটাল হাব" (31.99 s)
}


def write_js(path: Path) -> None:
    data = {"DURATION": DURATION, "BPM": BPM, "BEAT": BEAT, "GRID0": GRID0, "SCENES": SCENES, "CUES": CUES}
    path.write_text("// Generated by timeline.py, do not edit by hand.\nwindow.TL = "
                    + json.dumps(data, indent=1, ensure_ascii=False) + ";\n", encoding="utf-8")


if __name__ == "__main__":
    write_js(HERE / "timeline.js")
    print(f"wrote timeline.js  duration={DURATION}s  drop={bar(3)}s lift={bar(7)}s final={GRID0 + 53 * BEAT:.2f}s")
