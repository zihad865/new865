def write_js(path: Path) -> None:
    data = {"DURATION": DURATION, "B": B, "CUES": CUES}
    path.write_text("// Generated by timeline.py, do not edit by hand.\nwindow.TL = "
                    + json.dumps(data, indent=1) + ";\n", encoding="utf-8")


if __name__ == "__main__":
    out = Path(__file__).resolve().parent / "timeline.js"
    write_js(out)
    print(f"wrote {out}")
