#!/usr/bin/env python3
"""Single source of truth for the Digital Hub brag video timing.

Scene cuts sit on the music's bar lines (112 BPM, bar = 60/112*4 s), so the
picture and soundtrack (audio.py) move together. index.html loads timeline.js,
written by running this file.
"""
import json
from pathlib import Path

BPM = 112
BAR = 60 / BPM * 4                          # 2.142857 s
DURATION = round(BAR * 10, 2)               # 21.43: final chord on bar 9 + ring-out
B = [round(BAR * 2, 3), round(BAR * 4, 3), round(BAR * 7, 3)]   # 4.286, 8.571, 15.0

CUES = {
    # 1 · hook: a site you love
    "s1_browser": 0.0, "s1_cursor": [0.5, 1.65], "s1_like": 1.8,
    "s1_a": [0.25, 0.42, 0.59, 0.76],                 # পছন্দের / কোনো / Website / দেখে
    "s1_b": [2.0, 2.12, 2.24, 2.36, 2.48],            # আমারও / যদি / এমন / একটা / থাকত!
    "s1_out": B[0] - 0.42,                            # browser collapses into the link pill
    # 2 · reveal: one link in, your website out
    "s2_title": B[0] + 0.15, "s2_src": B[0] + 0.05, "s2_type": [B[0] + 0.3, 0.7],
    "s2_pk1": [5.25, 0.5], "s2_dots": [5.3, 5.38, 5.46, 5.54, 5.62, 5.7, 5.78],
    "s2_links": [5.8, 5.95, 6.1], "s2_pk2": [6.15, 0.45],
    "s2_dst": 6.3, "s2_blk": [6.55, 6.8, 7.05], "s2_scan": [6.5, 0.8], "s2_ok": 7.25,
    "s2_cap": 5.95, "s2_out": B[1] - 0.3,
    # 3 · highlights: features plug into the hub
    "s3_title": B[1] + 0.12,
    "s3_cards": [8.95, 9.9, 10.85, 11.8, 12.75, 13.7],
    # 4 · punchline: inbox
    "s4_reveal": [B[2] - 0.2, 0.55],
    "s4_chat": 15.3, "s4_b1": 15.45, "s4_typing": [15.95, 0.65], "s4_b2": 16.6,
    "s4_big": 17.35, "s4_btn": 17.9, "s4_end": round(BAR * 9, 3), "s4_pulse": 18.5,
}


def write_js(path: Path) -> None:
    data = {"DURATION": DURATION, "B": B, "BAR": BAR, "CUES": CUES}
    path.write_text("// Generated by timeline.py, do not edit by hand.\nwindow.TL = "
                    + json.dumps(data, indent=1) + ";\n", encoding="utf-8")


if __name__ == "__main__":
    out = Path(__file__).resolve().parent / "timeline.js"
    write_js(out)
    print(f"wrote {out}  duration={DURATION}s cuts={B}")
